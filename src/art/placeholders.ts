/**
 * 占位美术（设计文档 11.2：第一阶段用色块 + 标签跑通全流程）
 *
 * 全部用 Phaser Graphics 画，不依赖任何图片资源。
 * 热点命中区与这里的图形坐标是**成对设计**的：改图形时请同步改 data/hotspots.ts。
 * 按 H 键可切换热点轮廓显示，用来核对两者是否对齐。
 */

import Phaser from 'phaser';

type G = Phaser.GameObjects.Graphics;

// ── 小工具 ──────────────────────────────────────────────

function rect(g: G, x: number, y: number, w: number, h: number, color: number, alpha = 1): void {
  g.fillStyle(color, alpha);
  g.fillRect(x, y, w, h);
}

function line(g: G, x1: number, y1: number, x2: number, y2: number, color: number, width = 1, alpha = 1): void {
  g.lineStyle(width, color, alpha);
  g.lineBetween(x1, y1, x2, y2);
}

function poly(g: G, pts: readonly [number, number][], color: number, alpha = 1): void {
  g.fillStyle(color, alpha);
  g.fillPoints(
    pts.map(([x, y]) => new Phaser.Math.Vector2(x, y)),
    true,
  );
}

/** 由深到浅的横向色带，用来铺天空 / 海面 */
function bands(g: G, x: number, y: number, w: number, h: number, colors: readonly number[]): void {
  const step = h / colors.length;
  colors.forEach((c, i) => rect(g, x, y + i * step, w, step + 1, c));
}

/**
 * 径向光晕。
 *
 * Phaser 的 Graphics 没有渐变填充，同色低透明度的同心圆一圈圈叠上去
 * 就是天然的径向衰减。单张圆片的问题是圆周是硬的，两两重叠处还会
 * 二次叠加 —— 屏幕上能直接看到圆与圆相交的"透镜"弧线。
 */
function glow(g: G, cx: number, cy: number, radius: number, color: number, strength = 0.016, rings = 8): void {
  for (let i = rings; i >= 1; i--) {
    g.fillStyle(color, strength);
    g.fillCircle(cx, cy, (radius * i) / rings);
  }
}

