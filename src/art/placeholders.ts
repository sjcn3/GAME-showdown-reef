// ── 人物层（第 2 组 B5：待机呼吸）──────────────────────────

/**
 * 人物所在的深度：压在场景静态图（0）之上、动效层（20）之下。
 *
 * 放在动效层下面是故意的 —— 雨、尘埃、光晕都该从人**前面**过去；
 * 但人物必须压在自己的影子/湿地反光（属于静态图）上面。
 */
export const FIGURE_DEPTH = 10;

export interface FigureSpec {
  /** 画法。坐标是**绝对**的（和静态图共用一套坐标），容器只负责整体位移 */
  readonly paint: (g: G) => void;
  /** 脚底的 y。呼吸以它为原点 —— 缩放时脚必须钉在地上，否则人会在原地上下跳 */
  readonly footY: number;
  readonly periodMs: number;
}

/**
 * 谁出现在哪个场景。
 *
 * 甲：原来这三个人是直接画在场景大图里的（`paintDockExterior` 里调 `paintZhou`），
 * 于是整张图一动不动，人是"立绘"。要让他们呼吸，就不能和背景共用一张 Graphics ——
 * 缩放背景会把整个场景一起拉变形。所以人物各自独立成层，背景的绘制函数里
 * 留一行注释指到这里。
 *
 * 同框两个人物**周期必须不同**（3600 / 2950）：同步呼吸看起来像两个人在同时点头。
 */
export const SCENE_FIGURES: Readonly<Record<string, readonly FigureSpec[]>> = {
  dock_exterior: [{ paint: paintZhou, footY: 990, periodMs: 3400 }],
  warehouse_night: [
    { paint: paintChen, footY: 800, periodMs: 3600 },
    { paint: paintChief, footY: 800, periodMs: 2950 },
  ],
};

/** 呼吸幅度：±1.2% 的纵向缩放。再多就不是呼吸，是橡皮人 */
const BREATH_SCALE = 1.012;

/**
 * 把当前场景的人物各画一层，并挂上待机呼吸。
 *
 * 缩放的**原点在脚底**：容器摆在 `(0, footY)`，里面那张图整体上移 `footY`，
 * 这样缩放容器时脚的位置不动，只有上半身随着呼吸起伏（`y = footY + (Y-footY)*k`）。
 * Graphics 没有 origin，只能靠容器绕这一圈。
 */
export function addSceneFigures(scene: Phaser.Scene, paintKey: string): Phaser.GameObjects.Container[] {
  const specs = SCENE_FIGURES[paintKey];
  if (!specs) return [];

  return specs.map((spec) => {
    const art = scene.add.graphics();
    spec.paint(art);
    art.y = -spec.footY;
    const box = scene.add.container(0, spec.footY, [art]);
    box.setDepth(FIGURE_DEPTH);
    scene.tweens.add({
      targets: box,
      scaleY: BREATH_SCALE,
      duration: spec.periodMs,
      yoyo: true,
      repeat: -1,
      ease: 'Sine.easeInOut',
    });
    return box;
  });
}
